function record(name, start, segments, sampleEvery) {
  let hero = createHero(HOME_BLOCK, start);
  let input = { moveX: 0, moveZ: 0, jump: false, power: false };
  const samples = [];
  const events = [];
  let step = 0;
  for (const segment of segments) {
    const { steps, ...change } = segment;
    input = { ...input, ...change };
    for (let index = 0; index < steps; index++) {
      hero = stepHero(HOME_BLOCK, hero, input);
      step++;
      if (hero.events) events.push([step, hero.events]);
      if (step % sampleEvery === 0) samples.push([step, ...row(hero)]);
    }
  }
  samples.push([step, ...row(hero)]);
  return { name, start, segments, sampleEvery, steps: step, events, samples };
}
