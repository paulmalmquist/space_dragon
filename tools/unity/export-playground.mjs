import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Exports the Luke's Playground level, the block's scenery specs and the hero motion rules
// from TypeScript into generated C# for Unity:
//   node --experimental-strip-types tools/unity/export-playground.mjs [--verify]
// No Unity Editor, renderer or art is loaded. --verify regenerates in memory and fails
// when a committed file differs, so the C# data can never drift from its source.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const verify = process.argv.includes('--verify');
const load = path => import(pathToFileURL(join(root, path)).href);
const block = await load('src/game/traversal/home-block.ts');
const { LUKE_PLAYGROUND, PLAYSET } = await load('src/game/traversal/luke-playground.ts');
const { createHero, stepHero } = await load('src/game/traversal/hero.ts');
const { TRAVERSAL_STEP } = await load('src/game/traversal/tuning.ts');
const motion = await load('src/game/hero/person-motion.ts');

const sourceFiles = ['src/game/traversal/tuning.ts', 'src/game/traversal/world.ts', 'src/game/traversal/home-block.ts', 'src/game/traversal/hero.ts',
  'src/game/traversal/luke-playground.ts', 'src/game/hero/person-motion.ts'];
const aggregate = createHash('sha256');
for (const name of sourceFiles) {
  aggregate.update(name); aggregate.update('\0');
  aggregate.update((await readFile(join(root, name), 'utf8')).replaceAll('\r\n', '\n')); aggregate.update('\0');
}
const sourceFingerprint = aggregate.digest('hex');

const number = value => {
  if (!Number.isFinite(value)) throw new Error(`Non-finite value ${value}`);
  const text = String(value);
  return /[.e]/.test(text) ? text : `${text}.0`;
};
const quote = value => `"${String(value).replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
const fields = (object, names) => names.map(name => `${name} = ${typeof object[name] === 'number' ? number(object[name]) : typeof object[name] === 'boolean' ? object[name] : quote(object[name])}`).join(', ');
const header = source => ['// <auto-generated>', `// Generated by tools/unity/export-playground.mjs from ${source}.`,
  '// Do not edit by hand: change the TypeScript source and run the exporter.', '// </auto-generated>', 'namespace SpaceDragon.Traversal', '{'];

// ---------- Level ----------
const world = LUKE_PLAYGROUND;
const level = header('src/game/traversal/luke-playground.ts');
level.push("    /// <summary>Luke's Playground: the practice home block plus a generic backyard playset.</summary>");
level.push('    public static class LukePlaygroundData', '    {');
level.push(`        public const string WorldId = ${quote(world.id)};`);
level.push(`        public const string SourceFingerprint = ${quote(sourceFingerprint)};`, '');
level.push('        public static TraversalWorld Create()', '        {', '            return new TraversalWorld', '            {', '                id = WorldId,');
level.push(`                bounds = new WorldBounds { ${fields(world.bounds, ['minX', 'maxX', 'minZ', 'maxZ'])} },`);
level.push(`                spawn = new SpawnPose { ${fields(world.spawn, ['x', 'z', 'yaw'])} },`);
level.push('                solids = new[]', '                {');
for (const s of world.solids) {
  const slope = s.slope ? `, hasSlope = true, slopeAlongX = ${s.slope.axis === 'x'}, slopeAtMin = ${number(s.slope.atMin)}, slopeAtMax = ${number(s.slope.atMax)}` : '';
  const bounce = s.bounce ? `, bounce = ${number(s.bounce)}` : '';
  level.push(`                    new Solid { ${fields(s, ['id', 'kind', 'minX', 'maxX', 'minZ', 'maxZ', 'minY', 'maxY'])}${slope}${bounce}${s.house ? ', house = true' : ''} },`);
}
level.push('                },', '                anchors = new[]', '                {');
for (const a of world.anchors) level.push(`                    new Anchor { ${fields(a, ['id', 'x', 'y', 'z', 'floor', 'perch'])} },`);
level.push('                },', '                water = new[]', '                {');
for (const w of world.water) level.push(`                    new WaterZone { ${fields(w, ['id', 'minX', 'maxX', 'minZ', 'maxZ', 'surface', 'bed'])} },`);
level.push('                },', '                sparks = new[]', '                {');
for (const s of world.sparks) level.push(`                    new SparkSpot { ${fields(s, ['id', 'x', 'y', 'z'])} },`);
level.push('                },', '                recoveries = new[]', '                {');
for (const r of world.recoveries) level.push(`                    new Recovery { ${fields(r, ['id', 'x', 'y', 'z', 'yaw'])} },`);
level.push('                },', '            };', '        }', '');
level.push('        /// <summary>Playset shapes for drawing; collision comes from the solids above.</summary>');
level.push(`        public static readonly RectSpec PlaysetRamp = new RectSpec { id = "playset-ramp", ${fields(PLAYSET.ramp, ['minX', 'maxX', 'minZ', 'maxZ'])}, height = ${number(PLAYSET.deck.top)} };`);
level.push(`        public static readonly RectSpec PlaysetDeck = new RectSpec { id = "playset-deck", ${fields(PLAYSET.deck, ['minX', 'maxX', 'minZ', 'maxZ'])}, height = ${number(PLAYSET.deck.top)} };`);
level.push(`        public static readonly RectSpec PlaysetSlide = new RectSpec { id = "playset-slide", ${fields(PLAYSET.slide, ['minX', 'maxX', 'minZ', 'maxZ'])}, height = ${number(PLAYSET.slide.foot)} };`);
level.push(`        public static readonly RectSpec PlaysetBars = new RectSpec { id = "playset-bars", ${fields(PLAYSET.bars, ['minX', 'maxX', 'minZ', 'maxZ'])}, height = ${number(PLAYSET.bars.top)} };`);
level.push(`        public static readonly RectSpec PlaysetSandbox = new RectSpec { id = "playset-sandbox", ${fields(PLAYSET.sandbox, ['minX', 'maxX', 'minZ', 'maxZ', 'height'])} };`);
level.push(`        public const double PlaysetDeckThickness = ${number(PLAYSET.deck.thickness)}, PlaysetBarsThickness = ${number(PLAYSET.bars.thickness)};`);
level.push(`        public const double PlaysetMastX = ${number(PLAYSET.mast.x)}, PlaysetMastZ = ${number(PLAYSET.mast.z)}, PlaysetMastHeight = ${number(PLAYSET.mast.height)};`, '');

// Scripted probes: the C# port must land exactly where the TypeScript reference does.
const probes = [
  { name: 'ramp-deck-slide', start: { x: 0.15, z: -4, yaw: Math.PI / 2 }, segments: [{ seconds: 0.75, moveX: 1 }, { seconds: 0.5, moveX: 0 }, { seconds: 1.4, moveX: 1 }, { seconds: 0.4, moveX: 0 }] },
  { name: 'bars-run-and-drop', start: { x: 5.4, z: -2.3, yaw: Math.PI / 2, y: PLAYSET.bars.top }, segments: [{ seconds: 0.45, moveX: 1 }, { seconds: 0.6, moveX: 1, power: true }, { seconds: 0.8, moveX: 0, power: false }] },
  { name: 'yard-jump-to-mast', start: { x: 0.6, z: -1.2, yaw: 2.2 }, segments: [{ seconds: 0.25, moveX: 0.7, moveZ: -0.7 }, { seconds: 0.3, jump: true }, { seconds: 0.1, jump: false },
    { seconds: 2.5, power: true }, { seconds: 1, power: false, moveX: 0, moveZ: 0 }] },
  { name: 'door-gate-dock-swing', start: { x: world.spawn.x, z: world.spawn.z, yaw: world.spawn.yaw }, segments: [{ seconds: 0.5, moveZ: 1 }, { seconds: 0.2, moveZ: 0 },
    { seconds: 2.6, moveX: 1, moveZ: 0.12, power: true }, { seconds: 0.25, jump: true }, { seconds: 2.4, jump: false }, { seconds: 1.5, power: false, moveX: 0, moveZ: 0 }] },
];
level.push('        public static readonly PlaygroundProbe[] Probes =', '        {');
let probeSteps = 0;
for (const probe of probes) {
  let hero = createHero(world, probe.start);
  let input = { moveX: 0, moveZ: 0, jump: false, power: false };
  const collected = [], tethers = [];
  let events = 0;
  const segments = [];
  for (const { seconds, ...change } of probe.segments) {
    input = { ...input, ...change };
    const steps = Math.round(seconds / TRAVERSAL_STEP);
    segments.push({ steps, ...input });
    for (let index = 0; index < steps; index++) {
      hero = stepHero(world, hero, input);
      probeSteps++;
      events |= hero.events;
      if (hero.tetherId && !tethers.includes(hero.tetherId)) tethers.push(hero.tetherId);
      for (const spark of world.sparks) {
        if (!collected.includes(spark.id) && Math.hypot(spark.x - hero.x, spark.y - (hero.y + 0.9), spark.z - hero.z) <= 1.5) collected.push(spark.id);
      }
    }
  }
  const mode = hero.mode[0].toUpperCase() + hero.mode.slice(1);
  level.push('            new PlaygroundProbe', '            {');
  level.push(`                name = ${quote(probe.name)}, startX = ${number(probe.start.x)}, startZ = ${number(probe.start.z)}, startYaw = ${number(probe.start.yaw)}, hasStartY = ${probe.start.y !== undefined}, startY = ${number(probe.start.y ?? 0)},`);
  level.push(`                segments = new[] { ${segments.map(item => `new ProbeSegment { ${fields(item, ['steps', 'moveX', 'moveZ', 'jump', 'power']).replace(/steps = (\d+)\.0/, 'steps = $1')} }`).join(', ')} },`);
  level.push(`                endX = ${number(hero.x)}, endY = ${number(hero.y)}, endZ = ${number(hero.z)}, endVx = ${number(hero.vx)}, endVy = ${number(hero.vy)}, endVz = ${number(hero.vz)}, endYaw = ${number(hero.yaw)},`);
  level.push(`                endMode = HeroMode.${mode}, endGroundId = ${quote(hero.groundId)}, events = ${events},`);
  level.push(`                tethers = new string[] { ${tethers.map(quote).join(', ')} }, collected = new string[] { ${collected.map(quote).join(', ')} },`);
  level.push('            },');
}
level.push('        };', '    }', '}');

// ---------- Scenery specs ----------
const scenery = header('src/game/traversal/home-block.ts');
scenery.push('    /// <summary>What stands on the practice block, for drawing only. Collision never reads this.</summary>');
scenery.push('    public static class HomeBlockScenery', '    {');
scenery.push(`        public const double RoofThickness = ${number(block.ROOF_THICKNESS)}, HomeFloor = ${number(block.HOME_FLOOR)}, FenceHeight = ${number(block.FENCE_HEIGHT)}, ShoreX = ${number(block.SHORE_X)};`);
const houses = list => list.map(h => `            new HouseSpec { ${fields(h, ['id', 'minX', 'maxX', 'minZ', 'maxZ', 'wall', 'ridge', 'overhang', 'palette'])}, ridgeAlongX = ${h.ridgeAxis === 'x'}, home = ${Boolean(h.home)} },`);
const table = (type, name, rows) => scenery.push(`        public static readonly ${type}[] ${name} =`, '        {', ...rows, '        };');
table('HouseSpec', 'Houses', houses(block.HOUSES));
table('HouseSpec', 'BackdropHouses', houses(block.BACKDROP_HOUSES));
table('ArmSpec', 'Lamps', block.LAMPS.map(l => `            new ArmSpec { ${fields(l, ['id', 'x', 'z', 'height', 'armX', 'armZ', 'floor'])} },`));
table('ArmSpec', 'Poles', block.POLES.map(p => `            new ArmSpec { ${fields(p, ['id', 'x', 'z', 'height', 'armX', 'armZ'])} },`));
table('ArmSpec', 'Pilings', block.PILINGS.map(p => `            new ArmSpec { ${fields(p, ['id', 'x', 'z', 'height', 'armX', 'armZ'])} },`));
table('PalmSpec', 'Palms', block.PALMS.map(p => `            new PalmSpec { ${fields(p, ['id', 'x', 'z', 'height', 'leanX', 'leanZ', 'anchor'])} },`));
table('TreeSpec', 'Trees', block.TREES.map(t => `            new TreeSpec { ${fields(t, ['id', 'x', 'z', 'height', 'crown', 'limbX', 'limbZ'])} },`));
table('RectSpec', 'Cars', block.CARS.map(c => `            new RectSpec { ${fields(c, ['id', 'minX', 'maxX', 'minZ', 'maxZ', 'color'])}, height = 1.45 },`));
table('RectSpec', 'Fences', block.FENCES.map(f => `            new RectSpec { ${fields(f, ['id', 'minX', 'maxX', 'minZ', 'maxZ'])}, height = ${number(block.FENCE_HEIGHT)} },`));
table('RectSpec', 'Hedges', block.HEDGES.map(h => `            new RectSpec { ${fields(h, ['id', 'minX', 'maxX', 'minZ', 'maxZ', 'height'])} },`));
table('MastSpec', 'RoofMasts', block.ROOF_MASTS.map(m => `            new MastSpec { ${fields(m, ['id', 'x', 'z', 'height', 'ridge'])}, home = ${Boolean(m.home)} },`));
const constants = (prefix, object) => scenery.push(`        public const double ${Object.entries(object).filter(([, value]) => typeof value === 'number').map(([key, value]) => `${prefix}${key[0].toUpperCase()}${key.slice(1)} = ${number(value)}`).join(', ')};`);
constants('Dock', block.DOCK);
constants('Sandbar', block.SANDBAR);
constants('Trampoline', block.TRAMPOLINE);
constants('Gate', block.GATE);
constants('Garage', block.GARAGE);
constants('DockMast', block.DOCK_MAST);
scenery.push('    }', '}');

// ---------- Hero motion ----------
const person = header('src/game/hero/person-motion.ts');
person.push('    /// <summary>Numbers behind the realistic hero stand-in: loops, poses and reference samples.</summary>');
person.push('    public static class PersonMotionData', '    {');
person.push(`        public static readonly string[] ClipIds = { ${motion.LOCOMOTION.map(clip => quote(clip.id)).join(', ')} };`);
person.push(`        public static readonly double[] ClipSpeeds = { ${motion.LOCOMOTION.map(clip => number(clip.speed)).join(', ')} };`);
person.push(`        public static readonly double[] ClipDurations = { ${motion.LOCOMOTION.map(clip => number(clip.duration)).join(', ')} };`);
const M = motion.MOTION;
person.push(`        public const double MaxStrideRate = ${number(M.maxStrideRate)}, MinStrideRate = ${number(M.minStrideRate)}, BlendRate = ${number(M.blendRate)}, AirBlendRate = ${number(M.airBlendRate)}, SwingBlendRate = ${number(M.swingBlendRate)};`);
person.push(`        public const double LandBend = ${number(M.landBend)}, LandRecover = ${number(M.landRecover)}, LegLength = ${number(M.legLength)};`);
person.push(`        public const double BlinkSeconds = ${number(M.blinkSeconds)}, BlinkEveryMin = ${number(M.blinkEvery[0])}, BlinkEveryMax = ${number(M.blinkEvery[1])};`);
person.push(`        public const string GripBone = ${quote(motion.GRIP_BONE)}, HeadBone = ${quote(motion.HEAD_BONE)};`);
person.push('        public static readonly PoseSpec[] Poses =', '        {');
for (const pose of motion.POSES) {
  person.push(`            new PoseSpec { id = ${quote(pose.id)}, turns = new[]`, '            {');
  for (const item of pose.turns) person.push(`                new PoseTurn { bone = ${quote(item.bone)}, axis = '${item.axis}', degrees = ${number(item.degrees)}, landLeg = ${pose.id === 'land' && motion.LAND_LEG_BONES.includes(item.bone)} },`);
  person.push('            } },');
}
person.push('        };');
person.push('        public static readonly TetherArm[] TetherArms =', '        {');
for (const arm of motion.TETHER_ARMS) person.push(`            new TetherArm { ${fields(arm, ['bone', 'tip', 'weight'])} },`);
person.push('        };');
person.push('        /// <summary>Reference values computed by the TypeScript rules; the C# port must reproduce them.</summary>');
person.push('        public static readonly MotionSample[] Samples =', '        {');
for (const speed of [0, 0.2, 0.799, 1.4, 2.275, 3.3, 4.6, 4.613, 6, 8.2, 30]) {
  const weights = motion.locomotionWeights(speed);
  person.push(`            new MotionSample { speed = ${number(speed)}, idle = ${number(weights[0])}, walk = ${number(weights[1])}, run = ${number(weights[2])}, sprint = ${number(weights[3])}, stride = ${number(motion.strideCyclesPerSecond(weights, speed))} },`);
}
person.push('        };');
person.push(`        public static readonly double[] CrouchEnvelopes = { ${[0, 0.25, 0.5, 1].map(number).join(', ')} };`);
person.push(`        public static readonly double[] CrouchDrops = { ${[0, 0.25, 0.5, 1].map(value => number(motion.crouchDrop(value))).join(', ')} };`);
person.push('    }', '}');

const core = join(root, 'unity/SpaceDragon/Assets/SpaceDragon/Traversal/Core');
const outputs = [
  [join(core, 'LukePlaygroundData.cs'), `${level.join('\n')}\n`],
  [join(core, 'HomeBlockScenery.cs'), `${scenery.join('\n')}\n`],
  [join(core, 'PersonMotionData.cs'), `${person.join('\n')}\n`],
];
const summary = { sourceFingerprint, world: world.id, solids: world.solids.length, anchors: world.anchors.length, sparks: world.sparks.length, probes: probes.length, probeSteps };
if (verify) {
  const problems = [];
  for (const [path, expected] of outputs) {
    const actual = await readFile(path, 'utf8').catch(() => null);
    if (actual === null) problems.push(`${path} is missing; run the exporter without --verify`);
    else if (actual.replaceAll('\r\n', '\n') !== expected) problems.push(`${path} does not match the TypeScript source; run the exporter without --verify`);
  }
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  console.log(`PLAYGROUND_EXPORT_VERIFIED ${JSON.stringify(summary)}`);
} else {
  for (const [path, text] of outputs) await writeFile(path, text);
  console.log(`PLAYGROUND_EXPORT_OK ${JSON.stringify(summary)}`);
}
